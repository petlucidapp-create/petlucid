  function fallbackCalc(lang) {
    return CALC_STRINGS[lang] || CALC_STRINGS.en;
  }

  // ct('cardTitle') gibi düz anahtarlar; ct('animals.cat') gibi nokta-yollu erişim de desteklenir.
  function ct(key) {
    const lang = global.PLI18n ? global.PLI18n.currentLang() : 'tr';
    const block = fallbackCalc(lang);
    const parts = key.split('.');
    let val = block;
    for (const p of parts) {
      val = val && val[p] !== undefined ? val[p] : undefined;
    }
    if (val !== undefined) return val;
    // İngilizce'ye düş
    let enVal = CALC_STRINGS.en;
    for (const p of parts) {
      enVal = enVal && enVal[p] !== undefined ? enVal[p] : undefined;
    }
    return enVal !== undefined ? enVal : '';
  }

